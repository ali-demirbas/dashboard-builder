#!/usr/bin/env bash
# Builds dashboard-builder-consolidated.md by verbatim concatenation of the
# skill's 8 source files: SKILL.md, the 6 reference files, and
# scripts/README.md (SKILL.md lists it in its references table, so the
# consolidated copy carries it as the last Part). dbcalc's Python code is
# not included. Run from anywhere.
#
# Usage: build_consolidated.sh [OUTPUT_PATH]
#   Default output is dashboard-builder-consolidated.md at the repo root.
#   validate.sh passes a temp path to compare a fresh build with the
#   committed file without overwriting it.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$ROOT/dashboard-builder-consolidated.md}"
# Resolve a relative OUTPUT_PATH against the caller's directory, before cd.
case "$OUT" in /*) ;; *) OUT="$PWD/$OUT" ;; esac
cd "$ROOT" || exit 1
S="skills/dashboard-builder"
{
  echo "# Marketing & Growth Dashboard Builder — Consolidated Skill (8 files → 1)"
  echo
  echo "The entire \`dashboard-builder\` skill in one file: \`SKILL.md\`, all 6 reference files and \`scripts/README.md\`, verbatim, in load order (the \`dbcalc\` code itself is not included). Generated by \`scripts/build_consolidated.sh\`: edit the source files under \`$S/\`, never this file."
  n=1
  for f in SKILL.md references/data-quality-gate.md references/comparability-rules.md \
           references/kpi-framework.md references/analysis-playbook.md \
           references/dashboard-blueprints.md references/presentation-blueprints.md \
           scripts/README.md; do
    case "$f" in references/*) name="$(basename "$f")" ;; *) name="$f" ;; esac
    echo; echo "---"; echo
    echo "# PART $n — $name"
    echo
    cat "$S/$f"
    n=$((n+1))
  done
} > "$OUT"
echo "built $OUT ($(wc -w < "$OUT" | tr -d ' ') words)"
